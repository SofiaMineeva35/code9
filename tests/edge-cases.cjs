const assert = require('node:assert/strict')
const { chromium } = require('playwright')
;(async () => {
 const browser = await chromium.launch()
 const context = await browser.newContext({ viewport: { width: 390, height: 844 } })
 const page = await context.newPage(); await page.goto(process.env.BASE_URL || 'http://127.0.0.1:4173')
 await page.locator('#shortText').fill('Учебная проверка отказов')
 await page.locator('#email').fill('anna@example.com')
 await page.locator('#consent').check()
 // Управляем только тестовым окружением: локальное чтение ожидает отмены.
 await page.evaluate(() => { window.originalReader = window.FileReader; window.FileReader = class { readAsArrayBuffer() {} abort() {} } })
 await page.locator('input[type=file]').setInputFiles({ name: 'pending.txt', mimeType: 'text/plain', buffer: Buffer.from('test') })
 assert.equal(await page.getByRole('button', { name: 'Отправить запрос', exact: true }).isDisabled(), true)
 await page.getByRole('button', { name: 'Отменить pending.txt', exact: true }).click()
 assert.equal(await page.locator('.attachment').count(), 0)
 assert.equal(await page.getByRole('button', { name: 'Отправить запрос', exact: true }).isEnabled(), true)
 // Реальный обработчик onerror получает искусственный сбой чтения.
 await page.evaluate(() => { window.FileReader = class { readAsArrayBuffer() { setTimeout(() => this.onerror(), 0) } abort() {} } })
 await page.locator('input[type=file]').setInputFiles({ name: 'retry.txt', mimeType: 'text/plain', buffer: Buffer.from('test') })
 await page.getByText('Не удалось прочитать файл.', { exact: false }).waitFor()
 await page.evaluate(() => { window.FileReader = window.originalReader })
 await page.getByRole('button', { name: 'Повторить', exact: true }).click()
 await page.getByText(/КБ · Прикреплён/).waitFor()
 // Независимый отказ PDF не уничтожает бриф и не повторяет обработку запроса.
 await page.route('**/fonts/**', route => route.abort())
 await page.getByRole('button', { name: 'Отправить запрос', exact: true }).click()
 await page.getByText('Не удалось создать PDF.', { exact: false }).waitFor()
 await page.unroute('**/fonts/**')
 await page.getByRole('button', { name: 'Создать PDF повторно', exact: true }).click()
 await page.getByRole('button', { name: 'Скачать PDF', exact: true }).waitFor()
 await page.getByRole('button', { name: 'Вернуться к брифу', exact: true }).click()
 assert.equal(await page.locator('#shortText').inputValue(), 'Учебная проверка отказов')
 await page.evaluate(() => document.fonts.ready)
 const checkbox = await page.locator('.checkbox-mark').boundingBox()
 assert.equal(checkbox.width, 24); assert.equal(checkbox.height, 24)
 await page.screenshot({ path: 'test-results/mobile-final.png', fullPage: true })
 // Отказ хранилища не ломает ввод, предупреждение видно.
 const blocked = await context.newPage()
 await blocked.addInitScript(() => { Storage.prototype.setItem = () => { throw new Error('Storage blocked for test') } })
 await blocked.goto(process.env.BASE_URL || 'http://127.0.0.1:4173')
 await blocked.getByText('Браузер не разрешил сохранить черновик.', { exact: false }).waitFor()
 await blocked.locator('#shortText').fill('Ответ остаётся в памяти')
 assert.equal(await blocked.locator('#shortText').inputValue(), 'Ответ остаётся в памяти')
 await browser.close(); console.log('PASS: cancel, read failure/retry, PDF failure/retry, blocked storage, visible mobile checkbox')
})().catch(e => { console.error(e); process.exit(1) })
