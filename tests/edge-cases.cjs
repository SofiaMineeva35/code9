const assert = require('node:assert/strict')
const { chromium } = require('playwright')
const base = process.env.BASE_URL || 'http://127.0.0.1:4173'
;(async () => {
  const browser = await chromium.launch()
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } })
  const page = await context.newPage(); await page.goto(base)
  const button = name => page.getByRole('button', { name, exact: true })
  await page.locator('#shortText').fill('Учебная проверка отказов')
  await page.locator('#email').fill('anna@example.com'); await page.locator('#consent').check()
  // Artificial failures are confined to this disposable browser context.
  await page.evaluate(() => { window.originalReader = window.FileReader; window.FileReader = class { readAsArrayBuffer() {} abort() {} } })
  await page.locator('input[type=file]').setInputFiles({ name: 'pending.txt', mimeType: 'text/plain', buffer: Buffer.from('test') })
  assert.equal(await button('Подготовить бриф').isDisabled(), true)
  await page.getByRole('button', { name: 'Отменить pending.txt', exact: true }).click()
  assert.equal(await page.locator('.attachment').count(), 0)
  await page.evaluate(() => { window.FileReader = class { readAsArrayBuffer() { setTimeout(() => this.onerror(), 0) } abort() {} } })
  await page.locator('input[type=file]').setInputFiles({ name: 'retry.txt', mimeType: 'text/plain', buffer: Buffer.from('test') })
  await page.getByText('Не удалось прочитать файл.', { exact: false }).waitFor()
  await page.evaluate(() => { window.FileReader = window.originalReader })
  await button('Повторить').click(); await page.getByText(/выбран на устройстве/).waitFor()
  // A preparation failure keeps the form, attachments and data available for retry.
  await page.evaluate(() => { window.originalISOString = Date.prototype.toISOString; Date.prototype.toISOString = () => { throw new Error('Test preparation failure') } })
  await button('Подготовить бриф').click()
  await page.getByText('Не удалось подготовить бриф.', { exact: false }).waitFor()
  assert.equal(await page.locator('#shortText').inputValue(), 'Учебная проверка отказов')
  assert.equal(await page.locator('.attachment').count(), 1)
  await page.evaluate(() => { Date.prototype.toISOString = window.originalISOString })
  await page.route('**/fonts/**', route => route.abort())
  await button('Повторить подготовку').click()
  await page.getByText('Не удалось создать PDF.', { exact: false }).waitFor()
  assert.equal(await button('Краткий бриф').count(), 0)
  const snapshot = await page.evaluate(() => sessionStorage.getItem('code9.brief.result.v1'))
  await page.screenshot({ path: 'test-results/v5-mobile-pdf-error.png', fullPage: true })
  await page.unroute('**/fonts/**'); await button('Создать PDF повторно').click(); await button('Скачать PDF').waitFor()
  assert.equal(await page.evaluate(() => sessionStorage.getItem('code9.brief.result.v1')), snapshot)
  await button('Начать новое обращение').click()
  assert.equal(await page.locator('#shortText').inputValue(), '')
  const checkbox = await page.locator('.checkbox-mark').boundingBox(); assert.equal(checkbox.width, 24); assert.equal(checkbox.height, 24)
  // The longest mobile question determines the shared content height.
  await page.setViewportSize({ width: 320, height: 844 })
  await button('Интерактивный бриф').click(); await page.getByLabel('Есть идея нового продукта', { exact: true }).check()
  await button('Далее').scrollIntoViewIfNeeded()
  const measure = () => page.evaluate(() => ({ scroll: scrollY, actions: document.querySelector('.question-actions').getBoundingClientRect().top, height: document.querySelector('.question-body').getBoundingClientRect().height }))
  const before = await measure(); await button('Далее').click(); const after = await measure()
  assert.ok(Math.abs(before.height - after.height) < 1, JSON.stringify({ before, after }))
  assert.ok(Math.abs(before.scroll - after.scroll) < 1, JSON.stringify({ before, after }))
  assert.ok(Math.abs(before.actions - after.actions) < 1, JSON.stringify({ before, after }))
  const blocked = await context.newPage()
  await blocked.addInitScript(() => { Storage.prototype.setItem = () => { throw new Error('Storage blocked for test') } })
  await blocked.goto(base); await blocked.getByText('Браузер не разрешил сохранить черновик.', { exact: false }).waitFor()
  await blocked.locator('#shortText').fill('Ответ остаётся в памяти'); assert.equal(await blocked.locator('#shortText').inputValue(), 'Ответ остаётся в памяти')
  await browser.close(); console.log('PASS V5 edge cases: file cancel/retry, preparation retry, PDF retry, completed lock, stable mobile steps, blocked storage')
})().catch(error => { console.error(error); process.exit(1) })
